def _low(cell):
    cell = cell.strip()
    if cell == '':
        return None
    return int(cell.split('-')[0]) if '-' in cell else int(cell)


def _build(block):
    """Each column -> {raw lower bound: T}. Only the lower bound is used."""
    rows = [r.split(',') for r in block.strip().splitlines()]
    table = {}
    for j, col in enumerate(_COLS):
        d = {}
        for r in rows:
            t = int(r[0])
            lb = _low(r[j + 1] if j + 1 < len(r) else '')
            if lb is not None:
                assert lb not in d, \
                    "NEO9Q norm: duplicate lower bound {} in column {}".format(lb, col)
                d[lb] = t
        # Monotonicity guard: lower bounds must strictly decrease as T decreases.
        # This catches any newly introduced transcription error immediately.
        lbs = [lb for lb, _ in sorted(d.items(), key=lambda kv: -kv[1])]
        assert all(lbs[k] < lbs[k - 1] for k in range(1, len(lbs))), \
            "NEO9Q norm: non-monotonic lower bounds in column {}".format(col)
        table[col.lower()] = d
    return table


